export type MessageKey = keyof typeof messages;

let current: Lang = (localStorage.getItem("aj199.lang") as Lang) || "ru";
if (current !== "ru" && current !== "en") current = "ru";

export function lang(): Lang {
  return current;
}

export function setLang(value: Lang): void {
  current = value;
  localStorage.setItem("aj199.lang", value);
  document.documentElement.lang = value;
}

export function toggleLang(): Lang {
  setLang(current === "ru" ? "en" : "ru");
  return current;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let text = messages[key][current];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
